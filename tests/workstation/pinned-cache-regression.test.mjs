import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir, rename, writeFile } from 'node:fs/promises';
import { fixture, git, specRepository, repository, commitAll, toolkitRoot } from './helpers.mjs';
import { readJson, writeJson } from '../../packages/contracts/index.mjs';
import { productCache } from '../../packages/workstation/catalog.mjs';
import { prepareRegression } from '../../packages/workstation/regression.mjs';

test('regression fetches an absent exact product pin from its declared remote without changing the editing checkout', async t => {
  const f = await fixture(t), product = path.join(f.base, 'product'), source = path.join(f.base, 'spec');
  const old = await repository(product, { 'product.txt': 'old' });
  await specRepository(source);
  await git.addModule(source, { projectId: 'product', url: product, commit: old }, await git.inspect(source));
  const config = await readJson(path.join(source, 'workbench.yaml'));
  config.projects = [{ id: 'product', path: 'projects/product' }];
  await writeJson(path.join(source, 'workbench.yaml'), config);
  await commitAll(source);
  const options = { home: f.home, toolkitRoot, allowLocal: true };
  await mkdir(f.home, { recursive: true });
  const context = { root: source, options, git, store: { recordRegression() {} }, repositoryId: 'SPEC-bound' };
  const cache = await productCache(context, { url: product });
  assert.equal(await git.resolve(cache), old);
  await writeFile(path.join(product, 'product.txt'), 'new');
  await commitAll(product);
  const next = await git.resolve(product);
  const editing = path.join(source, 'projects/product');
  await git.fetch(editing);
  await git.pin(source, { projectId: 'product', commit: next }, await git.inspect(source));
  await commitAll(source);
  const specRef = await git.resolve(source);
  await git.command(editing, ['checkout', '--detach', old]);
  await writeFile(path.join(editing, 'draft.txt'), 'preserve');
  const before = await git.inspect(editing);
  const request = { repositoryId: 'SPEC-bound', operationId: 'OP-pin', input: { specRef, projects: {} } };
  const batch = await prepareRegression({ ...context, request });
  assert.equal(batch.projects[0].commit, next);
  assert.equal(batch.projects[0].recordedCommit, next);
  assert.equal(batch.projects[0].requestedRef, 'SPEC_PIN');
  assert.deepEqual(await git.inspect(editing), before);
  assert.equal(await readJson(path.join(f.home, 'regressions', batch.batchId, 'baseline.json')).then(x => x.projects[0].commit), next);
  const missing = '0'.repeat(old.length);
  await assert.rejects(prepareRegression({ ...context, request: { ...request, input: { specRef, projects: { product: missing } } } }), { code: 'GIT_COMMAND_FAILED' });
  await rename(product, `${product}-offline`);
  await assert.rejects(prepareRegression({ ...context, request: { ...request, input: { specRef, projects: { product: missing } } } }), { code: 'GIT_COMMAND_FAILED' });
  assert.deepEqual(await git.inspect(editing), before);
});
