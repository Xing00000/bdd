import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtemp, mkdir, readFile, rm, stat, symlink } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createTargetApp, initializeTargetDatabase } from '../src/fixtures/target-app.js';
import { initializeFixtureEnvironment } from '../src/fixtures/setup.js';
import { createGitAdapter } from '../src/adapters/git/index.js';

test('Target website enforces real A/B sessions, persistent edits and management denial', async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'workbench-target-'));
  const file = path.join(directory, 'target.e2e.sqlite'), password = 'fixture-secret';
  initializeTargetDatabase(file);
  const app = createTargetApp({ file, password });
  t.after(async () => { await app.close(); await rm(directory, { recursive: true, force: true }); });
  const db = new DatabaseSync(file); t.after(() => db.close());
  assert.equal((await app.inject({ method: 'POST', url: '/api/login', payload: { username: 'scenario_user', password: 'wrong' } })).statusCode, 401);
  const loginA = await app.inject({ method: 'POST', url: '/api/login', payload: { username: 'scenario_user', password } });
  assert.equal(loginA.statusCode, 200); assert.equal(loginA.json().role, 'A');
  const cookieA = String(loginA.headers['set-cookie']).split(';')[0];
  assert.match((await app.inject({ url: '/', headers: { cookie: cookieA } })).body, /data-testid="document-content" readonly/);
  assert.equal((await app.inject({ method: 'POST', url: '/api/document', headers: { cookie: cookieA }, payload: { content: 'denied write' } })).statusCode, 403);
  assert.equal((db.prepare('SELECT content FROM test_documents').get() as { content: string }).content, 'initial');
  db.prepare('UPDATE test_accounts SET role_code=? WHERE username=?').run('B', 'scenario_user');
  assert.equal((await app.inject({ url: '/api/session', headers: { cookie: cookieA } })).json().role, 'A', 'old session does not silently inherit new role');
  assert.equal((await app.inject({ method: 'POST', url: '/api/document', headers: { cookie: cookieA }, payload: { content: 'still denied' } })).statusCode, 403);
  await app.inject({ method: 'POST', url: '/api/logout', headers: { cookie: cookieA } });
  assert.equal((await app.inject({ url: '/api/session', headers: { cookie: cookieA } })).statusCode, 401);
  const loginB = await app.inject({ method: 'POST', url: '/api/login', payload: { username: 'scenario_user', password } });
  const cookieB = String(loginB.headers['set-cookie']).split(';')[0];
  assert.equal(loginB.json().role, 'B');
  assert.equal((await app.inject({ method: 'POST', url: '/api/document', headers: { cookie: cookieB }, payload: { content: 'edited' } })).statusCode, 200);
  const persisted = new DatabaseSync(file, { readOnly: true });
  assert.equal((persisted.prepare('SELECT content FROM test_documents').get() as { content: string }).content, 'edited'); persisted.close();
  const accountsBefore = db.prepare('SELECT * FROM test_accounts ORDER BY username').all();
  const denied = await app.inject({ url: '/manage-accounts', headers: { cookie: cookieB } });
  assert.equal(denied.statusCode, 403); assert.match(denied.body, /data-testid="access-denied"/);
  assert.equal((await app.inject({ method: 'POST', url: '/api/manage-accounts', headers: { cookie: cookieB }, payload: { role: 'admin' } })).statusCode, 403);
  assert.deepEqual(db.prepare('SELECT * FROM test_accounts ORDER BY username').all(), accountsBefore);
  assert.equal((await app.inject({ method: 'POST', url: '/api/document', headers: { cookie: cookieB, origin: 'https://untrusted.example' }, payload: { content: 'cross-origin' } })).statusCode, 403);
  db.prepare('UPDATE test_accounts SET state=? WHERE username=?').run('disabled', 'scenario_user');
  assert.equal((await app.inject({ method: 'POST', url: '/api/document', headers: { cookie: cookieB }, payload: { content: 'inactive denied' } })).statusCode, 401);
});

test('Fixture setup preserves existing data, writes a private environment file and CI rejects empty specifications', async t => {
  const workspaceRoot = await mkdtemp(path.join(os.tmpdir(), 'workbench-setup-'));
  t.after(async () => { await rm(workspaceRoot, { recursive: true, force: true }); });
  await symlink(path.resolve('node_modules'), path.join(workspaceRoot, 'node_modules'), 'dir');
  const fixture = await initializeFixtureEnvironment({ workspaceRoot, password: 'fixture-only-password' });
  const db = new DatabaseSync(fixture.targetDb);
  db.prepare('UPDATE test_documents SET content=?').run('preserve existing data'); db.close();
  await initializeFixtureEnvironment({ workspaceRoot, password: 'fixture-only-password' });
  const again = new DatabaseSync(fixture.targetDb);
  assert.equal((again.prepare('SELECT content FROM test_documents').get() as { content: string }).content, 'preserve existing data'); again.close();
  assert.equal((await stat(path.join(fixture.root, 'product.env'))).mode & 0o777, 0o600);
  const adapter = createGitAdapter({ workspaceRoot });
  const empty = await adapter.runCi({ repo: fixture.targetRepo, commit: fixture.sourceRef });
  assert.equal(empty.status, 'FAILED'); assert.equal(empty.exitCode, 2); assert.match(empty.stderr, /CI_NOT_RUN: no saved standard spec/);
  const saved = await adapter.save({ repo: fixture.targetRepo, files: [{ path: 'example.spec.ts', rawText: 'export {};\n' }] });
  const unconfigured = await adapter.runCi({ repo: fixture.targetRepo, commit: saved.commit, env: { WB_RUN_ID: '' } });
  assert.equal(unconfigured.status, 'FAILED'); assert.match(unconfigured.stderr, /CI_NOT_RUN: missing/);
  assert.match(await readFile(path.join(fixture.root, 'product.env'), 'utf8'), /WB_TARGET_DB=/);
  await mkdir(path.join(workspaceRoot, 'elsewhere'));
  await assert.rejects(initializeFixtureEnvironment({ workspaceRoot, root: path.join(workspaceRoot, 'elsewhere') }), /dedicated .test-fixtures/);
});
