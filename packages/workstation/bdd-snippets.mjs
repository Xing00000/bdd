/** Native playwright-bdd snippet adapter, run with the prepared Spec Repo dependencies. */
import path from 'node:path';
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';

const root=process.cwd(),require=createRequire(path.join(root,'package.json'));
const packageRoot=path.dirname(require.resolve('playwright-bdd/package.json'));
const native=relative=>require(path.join(packageRoot,'dist',relative));
const {loadConfig}=native('playwright/loadConfig.js');
const {getEnvConfigs}=native('config/env.js');
const {TestFilesGenerator}=native('generate/index.js');
const {Snippet}=native('snippets/snippet.js');
native('cli/helpers/bddgenPhase.js').setBddGenPhase();
await loadConfig('bdd.config.ts');
const configs=Object.values(getEnvConfigs());
if(configs.length!==1)throw new Error('Skeleton generation requires exactly one BDD configuration');
const generator=new TestFilesGenerator(configs[0]);
await Promise.all([generator.loadFeatures(),generator.loadSteps()]);
await generator.handleImportTestFrom();
const selected=path.resolve(root,'spec',process.env.WB_REQUIREMENT_ID,process.env.WB_FEATURE_ID,process.env.WB_FEATURE_ID+'.feature');
const loaded=generator.featuresLoader.getDocumentsWithPickles();
if(loaded.length!==1||path.resolve(root,loaded[0].uri)!==selected)throw new Error('BDD configuration must load exactly the selected Gherkin: '+selected);
generator.buildFiles();
const snippets=new Set();
for(const file of generator.files)for(const step of file.getMissingSteps()) {
  const snippet=new Snippet(step,{isPlaywrightStyle:true,isTypeScript:true,isDecorator:false});
  snippets.add(snippet.code.replace('  // {step}',"  throw new Error('Step implementation required');").replace('  // {location}','  // Generated by playwright-bdd; complete before confirming the test plan.'));
}
const destination=process.argv[2],shared=path.relative(path.dirname(destination),'tests/_shared/bdd').split(path.sep).join('/');
await writeFile(destination,`import { Given, When, Then } from '${shared.startsWith('.')?shared:'./'+shared}';\nimport type { DataTable } from 'playwright-bdd';\n\n${[...snippets].join('\n\n')}\n`);
console.log(`[bddgen] Generated ${snippets.size} native step definitions`);
